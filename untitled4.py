"""
Aplicacion de PEP 8, Clean Code y funciones puras.
"""


def clean_data(data):
    """Elimina valores None y numeros negativos."""
    return [
        float(value)
        for value in data
        if value is not None and value >= 0
    ]


def calculate_mean(data):
    """Calcula la media aritmetica."""
    if not data:
        return None

    return sum(data) / len(data)


def calculate_variance(data, mean):
    """Calcula la varianza poblacional."""
    if not data:
        return None

    return sum(
        (value - mean) ** 2
        for value in data
    ) / len(data)


def calculate_std_dev(variance):
    """Calcula la desviacion estandar."""
    if variance is None:
        return None

    return variance ** 0.5


def calculate_statistics(data):
    """Coordina el calculo de estadisticas descriptivas."""

    clean_values = clean_data(data)

    if not clean_values:
        return None

    mean = calculate_mean(clean_values)
    variance = calculate_variance(clean_values, mean)
    std_dev = calculate_std_dev(variance)

    return {
        "mean": mean,
        "variance": variance,
        "standard_deviation": std_dev
    }


