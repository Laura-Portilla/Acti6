temperaturas = [25.4, 12.8, 35.1, 4.2, 18.5]

n = len(temperaturas)

for i in range(n):
    minimo = i

    for j in range(i + 1, n):
        if temperaturas[j] < temperaturas[minimo]:
            minimo = j

    temperaturas[i], temperaturas[minimo] = temperaturas[minimo], temperaturas[i]

print("Temperaturas ordenadas de menor a mayor:")
print(temperaturas)

